  @override
  Widget build(BuildContext context) {
    return Column(
      children: [
        for (final job in project.jobs) ...[
          _ProjectJobCard(job: job),
          const SizedBox(height: 18),
        ],
      ],
    );
  }
}

class _ProjectJobCard extends StatelessWidget {
  const _ProjectJobCard({required this.job});

  final EmployeeProjectJobItem job;

  @override
  Widget build(BuildContext context) {
    final inProgress = job.status == 'IN PROGRESS';

    return Container(
      padding: const EdgeInsets.fromLTRB(18, 18, 18, 18),
      decoration: BoxDecoration(
        color: AppColors.white,
        borderRadius: BorderRadius.circular(20),
        border: Border.all(color: AppColors.borderLight),
        boxShadow: const [
          BoxShadow(
            color: Color(0x0F000000),
            blurRadius: 14,
            offset: Offset(0, 8),
          ),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              _ProjectJobStatusChip(status: job.status),
              const Spacer(),
              Column(
                crossAxisAlignment: CrossAxisAlignment.end,
                children: [
                  Text(
                    'Earning',
                    style: AppFonts.labelSmall(
                      color: AppColors.muted,
                    ).copyWith(fontWeight: FontWeight.w700),
                  ),
                  const SizedBox(height: 2),
                  Text(
                    job.earning,
                    style: AppFonts.titleSmall(
                      color: inProgress
                          ? const Color(0xFF00A553)
                          : AppColors.inkStrong,
                    ).copyWith(fontWeight: FontWeight.w900),
                  ),
                ],
              ),
            ],
          ),
          const SizedBox(height: 8),
          Text(
            job.title,
            style: AppFonts.titleLarge(
              color: AppColors.inkStrong,
            ).copyWith(fontWeight: FontWeight.w900, fontSize: 19, height: 1.1),
          ),
          const SizedBox(height: 15),
          _ProjectJobMetaRow(
            icon: Icons.location_on_rounded,
            label: job.location,
          ),
          const SizedBox(height: 9),
          _ProjectJobMetaRow(
            icon: Icons.access_time_rounded,
            label: job.schedule,
          ),
          const SizedBox(height: 20),
          SizedBox(
            width: double.infinity,
            height: 52,
            child: FilledButton(
              onPressed: () {
                context.push(
                  EmployeeJobDetailsPage.path,
                  extra: <String, Object?>{'jobId': job.title.hashCode},
                );
              },
              style: FilledButton.styleFrom(
                backgroundColor: AppColors.inkStrong,
                foregroundColor: AppColors.white,
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(9),
                ),
              ),
              child: Text(
                job.actionLabel,
                style: AppFonts.titleSmall(
                  color: AppColors.white,
                ).copyWith(fontWeight: FontWeight.w900),
              ),
            ),
          ),
        ],
      ),
    );
  }
}

class _ProjectJobStatusChip extends StatelessWidget {
  const _ProjectJobStatusChip({required this.status});

  final String status;

  @override
  Widget build(BuildContext context) {
    final color = switch (status) {
      'IN PROGRESS' => const Color(0xFF5E4BFF),
      'UPCOMING' => const Color(0xFFE34D1C),
      _ => AppColors.muted,
    };
    final bg = switch (status) {
      'IN PROGRESS' => const Color(0xFFF1EFFF),
      'UPCOMING' => const Color(0xFFFFF0E8),
      _ => AppColors.surfaceHigh,
    };
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 5),
      decoration: BoxDecoration(
        color: bg,
        borderRadius: BorderRadius.circular(5),
      ),
      child: Text(
        status,
        style: AppFonts.labelSmall(
          color: color,
        ).copyWith(fontWeight: FontWeight.w900, fontSize: 9),
      ),
    );
  }
}

class _ProjectJobMetaRow extends StatelessWidget {
  const _ProjectJobMetaRow({required this.icon, required this.label});

  final IconData icon;
  final String label;

  @override
  Widget build(BuildContext context) {
    return Row(
      children: [
        Icon(icon, size: 19, color: AppColors.muted),
        const SizedBox(width: 9),
        Expanded(
          child: Text(
            label,
            maxLines: 1,
            overflow: TextOverflow.ellipsis,
            style: AppFonts.bodyMedium(
              color: AppColors.inkStrong,
            ).copyWith(fontWeight: FontWeight.w700),
          ),
        ),
      ],
    );
  }
}

class _ProjectErrorState extends StatelessWidget {
  const _ProjectErrorState({required this.message, required this.onRetry});

  final String message;
  final VoidCallback onRetry;

  @override
  Widget build(BuildContext context) {
    return Center(
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Text(message, style: AppFonts.bodyMedium(color: AppColors.error)),
          const SizedBox(height: 12),
          OutlinedButton(onPressed: onRetry, child: const Text('Retry')),
        ],
      ),
    );
  }
}

class _ProjectEmptyState extends StatelessWidget {
  const _ProjectEmptyState();

  @override
  Widget build(BuildContext context) {
    return Center(
      child: Text(
        'No project details found.',
        style: AppFonts.bodyMedium(color: AppColors.muted),
      ),
    );
  }
}
