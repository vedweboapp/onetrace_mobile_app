class EmployeeProjectDetailsPage extends ConsumerStatefulWidget {
  const EmployeeProjectDetailsPage({super.key, this.projectName});

  static const path = '/employee-role/projects/detail';
  static const name = 'employee-project-detail';

  final String? projectName;

  @override
  ConsumerState<EmployeeProjectDetailsPage> createState() =>
      _EmployeeProjectDetailsPageState();
}

class _EmployeeProjectDetailsPageState
    extends ConsumerState<EmployeeProjectDetailsPage> {
  @override
  void initState() {
    super.initState();
    Future.microtask(() {
      ref
          .read(employeeProjectDetailControllerProvider.notifier)
          .load(projectName: widget.projectName);
    });
  }

  @override
  Widget build(BuildContext context) {
    final state = ref.watch(employeeProjectDetailControllerProvider);
    final controller = ref.read(
      employeeProjectDetailControllerProvider.notifier,
    );
    final project = state.project;

    return Scaffold(
      backgroundColor: AppColors.white,
      appBar: AppBar(
        backgroundColor: AppColors.white,
        foregroundColor: AppColors.inkStrong,
        elevation: 0,
        scrolledUnderElevation: 0,
        toolbarHeight: 52,
        leadingWidth: 42,
        titleSpacing: 0,
        leading: IconButton(
          onPressed: () {
            if (context.canPop()) context.pop();
          },
          icon: const Icon(Icons.arrow_back_rounded, size: 22),
        ),
        title: Text(
          project?.title ?? widget.projectName ?? 'Project Details',
          maxLines: 1,
          overflow: TextOverflow.ellipsis,
          style: AppFonts.titleMedium(
            color: AppColors.inkStrong,
          ).copyWith(fontWeight: FontWeight.w900),
        ),
        bottom: const PreferredSize(
          preferredSize: Size.fromHeight(1),
          child: Divider(height: 1, color: AppColors.borderLight),
        ),
      ),
      body: state.isLoading
          ? const Center(child: CircularProgressIndicator())
          : state.errorMessage != null
          ? _ProjectErrorState(
              message: state.errorMessage!,
              onRetry: () => controller.load(projectName: widget.projectName),
            )
          : project == null
          ? const _ProjectEmptyState()
          : Column(
              children: [
                EmployeeProjectTabs(
                  selectedTab: state.selectedTab,
                  onChanged: controller.selectTab,
                ),
                Expanded(
                  child: ListView(
                    padding: const EdgeInsets.fromLTRB(16, 18, 16, 28),
                    children: [
                      if (state.selectedTab ==
                          EmployeeProjectDetailTab.overview)
                        EmployeeProjectOverview(project: project)
                      else
                        EmployeeProjectJobs(project: project),
                    ],
                  ),
                ),
              ],
            ),
    );
  }
}

class EmployeeProjectTabs extends StatelessWidget {
  const EmployeeProjectTabs({
    super.key,
    required this.selectedTab,
    required this.onChanged,
  });

  final EmployeeProjectDetailTab selectedTab;
  final ValueChanged<EmployeeProjectDetailTab> onChanged;

  @override
  Widget build(BuildContext context) {
    return Container(
      decoration: const BoxDecoration(
        border: Border(bottom: BorderSide(color: AppColors.borderLight)),
      ),
      child: Row(
        children: [
          _ProjectDetailTabButton(
            label: 'Overview',
            selected: selectedTab == EmployeeProjectDetailTab.overview,
            onTap: () => onChanged(EmployeeProjectDetailTab.overview),
          ),
          _ProjectDetailTabButton(
            label: 'Jobs',
            selected: selectedTab == EmployeeProjectDetailTab.jobs,
            onTap: () => onChanged(EmployeeProjectDetailTab.jobs),
          ),
        ],
      ),
    );
  }
}

class _ProjectDetailTabButton extends StatelessWidget {
  const _ProjectDetailTabButton({
    required this.label,
    required this.selected,
    required this.onTap,
  });

  final String label;
  final bool selected;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    return Expanded(
      child: InkWell(
        onTap: onTap,
        child: Container(
          height: 48,
          alignment: Alignment.center,
          decoration: BoxDecoration(
            border: Border(
              bottom: BorderSide(
                color: selected ? AppColors.inkStrong : AppColors.transparent,
                width: 2,
              ),
            ),
          ),
          child: Text(
            label,
            style: AppFonts.labelLarge(
              color: selected ? AppColors.inkStrong : AppColors.muted,
            ).copyWith(fontWeight: FontWeight.w900),
          ),
        ),
      ),
    );
  }
}

